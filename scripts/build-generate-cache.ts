/**
 * Pre-generate fit scores and post concepts for the demo profile so the demo works offline.
 * Uses the cached safety verdicts to decide which trends are safe, then calls the live LLM:
 * one fit-scoring call for all safe trends and one concept call per safe trend.
 * Writes data/cache/fit-scores.json, data/cache/concepts.json and docs/test-evidence/generate-run.md.
 *
 * Usage: npm run cache:generate
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadEnvConfig } from "@next/env";
import { callStructured, getModel, LlmError } from "../lib/llm/client";
import { DEMO_PROFILE } from "../lib/profile/schema";
import { CONCEPT_PROMPT_VERSION, conceptCacheKey, generateConcepts } from "../lib/generate/concepts";
import { FIT_PROMPT_VERSION, fitCacheKey, scoreTrends } from "../lib/generate/fit";
import type { ConceptCache, FitCache } from "../lib/generate/schemas";
import { loadSafetyCache } from "../lib/safety/cache";
import { filterTrends } from "../lib/safety/filter";
import { createSafetyChecker } from "../lib/safety/llm-check";
import { loadSavedSnapshot } from "../lib/youtube/snapshot";

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ");

async function main() {
  loadEnvConfig(process.cwd());
  const model = getModel();
  const now = new Date().toISOString();
  const profile = DEMO_PROFILE;

  // Safe trends from cached verdicts only (no LLM calls for safety).
  const { kept } = await filterTrends(loadSavedSnapshot().items, {
    topicsToAvoid: profile.topicsToAvoid,
    checker: createSafetyChecker({ cache: loadSafetyCache() }),
  });
  const items = kept.map((k) => k.item);
  console.log(`${items.length} safe trends. Scoring fit...`);

  const fit = await scoreTrends(items, profile, { caller: callStructured });
  if (fit.source !== "llm" || fit.scores.size !== items.length) {
    console.error(`Fit scoring failed or incomplete (${fit.scores.size}/${items.length}): ${fit.error ?? ""}`);
    process.exit(1);
  }

  console.log("Generating concepts (one call per trend)...");
  const conceptResults = await Promise.all(
    items.map(async (item) => {
      try {
        return { item, result: await generateConcepts(item, profile, { caller: callStructured }) };
      } catch (err) {
        return { item, error: err instanceof LlmError ? err.message : String(err) };
      }
    }),
  );
  const failed = conceptResults.filter((r) => "error" in r);
  if (failed.length > 0) {
    for (const f of failed) console.error(`  ${f.item.id}: ${"error" in f ? f.error : ""}`);
    console.error("Some concept calls failed. Caches not written; run again.");
    process.exit(1);
  }

  const fitCache: FitCache = {
    promptVersion: FIT_PROMPT_VERSION,
    model,
    entries: { [fitCacheKey(items, profile)]: { scores: [...fit.scores.values()], createdAt: now } },
  };
  const conceptCache: ConceptCache = { promptVersion: CONCEPT_PROMPT_VERSION, model, entries: {} };
  for (const r of conceptResults) {
    if ("result" in r && r.result) {
      conceptCache.entries[conceptCacheKey(r.item, profile)] = { concepts: r.result.concepts, createdAt: now };
    }
  }
  writeFileSync(join("data", "cache", "fit-scores.json"), JSON.stringify(fitCache, null, 2) + "\n", "utf8");
  writeFileSync(join("data", "cache", "concepts.json"), JSON.stringify(conceptCache, null, 2) + "\n", "utf8");

  const ranked = [...items].sort((x, y) => fit.scores.get(y.id)!.score - fit.scores.get(x.id)!.score);
  const md: string[] = [
    "# Fit scoring and concept generation run (test evidence)",
    "",
    `Generated by \`npm run cache:generate\` on ${now} with model \`${model}\` (prompts \`${FIT_PROMPT_VERSION}\`, \`${CONCEPT_PROMPT_VERSION}\`) for the fictional demo profile "${profile.businessName}".`,
    "Every concept passed zod validation and the originality check (no copied titles or channel names). All posts still need human approval.",
    "",
    "## Fit scores",
    "",
    "| Score | Category | Trend | Reason |",
    "|---|---|---|---|",
    ...ranked.map((i) => {
      const s = fit.scores.get(i.id)!;
      return `| ${s.score} | ${i.categoryName} | ${cell(i.title)} | ${cell(s.reason)} |`;
    }),
    "",
    "## Concepts for the top-scoring trend",
    "",
  ];
  const top = conceptResults.find((r) => r.item.id === ranked[0].id);
  if (top && "result" in top && top.result) {
    md.push(`Trend: ${cell(top.item.title)} (${top.item.url})`, "");
    top.result.concepts.forEach((c, n) => {
      md.push(
        `### Concept ${n + 1}`,
        "",
        `- **Hook:** ${c.hook}`,
        `- **Caption:** ${c.caption}`,
        `- **Visual idea:** ${c.visualIdea}`,
        `- **Hashtags:** ${c.hashtags.join(" ")}`,
        `- **Platform:** ${c.platform}`,
        `- **Posting window:** ${c.postingWindow}`,
        "",
      );
    });
  }
  mkdirSync(join("docs", "test-evidence"), { recursive: true });
  writeFileSync(join("docs", "test-evidence", "generate-run.md"), md.join("\n"), "utf8");

  for (const i of ranked) console.log(`  ${String(fit.scores.get(i.id)!.score).padStart(3)}  ${i.title.slice(0, 60)}`);
  console.log(`Cached fit scores and ${Object.keys(conceptCache.entries).length} concept sets.`);
  console.log("Evidence written to docs/test-evidence/generate-run.md");
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
